public static String generateConfNumber(String transactionType) {
            Random random = new Random();

    long min = 1_000_000_000L; // Smallest 10-digit number
        long max = 9_999_999_999L; // Largest 10-digit number
        long randomNumber = min + (long)(random.nextDouble() * (max - min + 1));
        
        
  
        
        
        
        
    if (transactionType == "Return") {
        return "R" + randomNumber;
    }else if (transactionType == "Prepaid Single Activation") {
    return "PRP" + randomNumber;
 
    } else if (transactionType == "Prepaid Multiple Activation") {
    return "PRPD" + randomNumber;
 
    } else if (transactionType == "Postpaid Single Activation") {
    return "POP" + randomNumber;
 
    } 
    else if (transactionType == "Postpaid Multiple Activation") {
    return "POPD" + randomNumber;
 
    } 
    else if (transactionType == "Prepaid Addon Activation") {
    return "PRD" + randomNumber;
 
    } 
    else if (transactionType == "Postpaid Addon Activation") {
    return "POD" + randomNumber;
 
    } 
    else if (transactionType == "Service") {
    return "SRV" + randomNumber;
 
    } 
    else if (transactionType == "Accessory") {
    return "ACC" + randomNumber;
 
    } 
    else if (transactionType == "Activation Fee") {
    return "AF" + randomNumber;
 
    } 
    else{
    return "OT" + randomNumber;
 
    } 
    
    

}

   public static void setEnabledRecursive(Container container, boolean enabled) {
        for (Component c : container.getComponents()) {

            // Text fields and combo boxes are controlled by the flag
            if (c instanceof JTextField || c instanceof JComboBox || c instanceof JButton) {
                c.setEnabled(enabled);
            }

            // Recurse into nested panels/containers
            if (c instanceof Container) {
                setEnabledRecursive((Container) c, enabled);
            }
        }
    }


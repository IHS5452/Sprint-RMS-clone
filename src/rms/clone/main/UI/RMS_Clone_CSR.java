public static void getServices(String phoneNumber) {
    DefaultTableModel model = (DefaultTableModel) services_table.getModel();
    model.setRowCount(0);

    // Decide which phone number to use
    String lineNumber;
    if (phoneNumber == null || phoneNumber.isBlank()) {
        // fallback to currently selected customer’s phone
        lineNumber = vars.selectedCx != null ? vars.selectedCx.getContactPhone1() : null;
    } else {
        lineNumber = phoneNumber;
    }

    if (lineNumber == null || lineNumber.isBlank()) {
        JOptionPane.showMessageDialog(null, "No phone number provided or selected.");
        return;
    }

    String SQL_getLineServices =
        "SELECT associated_service_id " +
        "FROM customer_services_list " +
        "WHERE assosiated_phone_number = ?";

    try (PreparedStatement ps = vars.conn.prepareStatement(SQL_getLineServices)) {
        ps.setString(1, lineNumber);

        try (ResultSet rs = ps.executeQuery()) {

            boolean hasAny = false;

            while (rs.next()) {
                hasAny = true;

                int serviceId = rs.getInt("associated_service_id");

                // Static call, no need to new Services()
                Services service = Services.selectServiceById(serviceId);
                if (service == null) {
                    continue; // nothing to add
                }

                Object falloff =
                    (service.getFalloffDate() != null)
                    ? service.getFalloffDate()
                    : "Never";

                Object[] row = {
                    service.getServiceId(),
                    service.getServiceName(),
                    service.getEffectiveDate(),
                    falloff
                };

                model.addRow(row);
            }

            if (!hasAny) {
                System.out.println("No Services for this line. ");
            }
        }

    } catch (SQLException ex) {
        Logger.getLogger(RMS_Clone_CSR.class.getName()).log(Level.SEVERE, null, ex);
    }
}



public static void getNotes(String accountNumber) {
    try {
        DefaultTableModel model = (DefaultTableModel) notes_table.getModel();
        model.setRowCount(0); // Clear existing rows
        
        PreparedStatement stmt = vars.conn.prepareStatement(
            "SELECT * FROM account_notes WHERE account_number = ?"
        );
        stmt.setString(1, accountNumber);
        ResultSet rs = stmt.executeQuery();
        
        while (rs.next()) {
            Timestamp createdAt = rs.getTimestamp("created_at");
            String noteContent = rs.getString("note_content");
            int createdByPid = rs.getInt("created_by_pid");
            int noteID = rs.getInt("note_id");

            
            // Get first 6 words of the note
            String[] words = noteContent.split("\\s+");
            StringBuilder firstSixWords = new StringBuilder();
            for (int i = 0; i < Math.min(6, words.length); i++) {
                firstSixWords.append(words[i]);
                if (i < Math.min(6, words.length) - 1) {
                    firstSixWords.append(" ");
                }
            }
            
            // Add a new row to the table
            model.addRow(new Object[]{
                Integer.toString(noteID),
                firstSixWords.toString(), 
                createdByPid,
                                createdAt
            });
        }
        
    } catch (SQLException ex) {
        Logger.getLogger(RMS_Clone_CSR.class.getName()).log(Level.SEVERE, null, ex);
    }
}





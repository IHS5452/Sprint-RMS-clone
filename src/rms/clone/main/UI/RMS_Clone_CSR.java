private String normalizeDate(String input) {
    if (input == null || input.isEmpty()) return null;

    java.time.LocalDate date = null;
    java.time.format.DateTimeFormatter OUTPUT_FORMAT =
            java.time.format.DateTimeFormatter.ofPattern("MM/dd/yyyy");

    // Try 8-digit input: MMddyyyy
    if (input.matches("\\d{8}")) {
        try {
            String mm = input.substring(0, 2);
            String dd = input.substring(2, 4);
            String yyyy = input.substring(4);
            date = java.time.LocalDate.parse(mm + "/" + dd + "/" + yyyy, OUTPUT_FORMAT);
        } catch (Exception ignored) {}
    }

    // Try other patterns
    if (date == null) {
        String[] patterns = {
            "MM-dd-yyyy", "MM/dd/yyyy", "MM.dd.yyyy",
            "yyyy-MM-dd", "yyyy/MM/dd", "yyyy.MM.dd"
        };

        for (String p : patterns) {
            try {
                java.time.format.DateTimeFormatter fmt =
                        java.time.format.DateTimeFormatter.ofPattern(p);
                date = java.time.LocalDate.parse(input, fmt);
                break;
            } catch (Exception ignored) {}
        }
    }

    return (date != null) ? date.format(OUTPUT_FORMAT) : null;
}



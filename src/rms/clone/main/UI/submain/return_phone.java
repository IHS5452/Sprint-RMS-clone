                                                   rid_txt.setEditable(false);
                                       eligable_txt.setText("");
                                       status_cb.setSelectedIndex(0);
                                       rid_txt.setText("");
                                       vars.hasManagerAuth = false;
            new_return_bttn.setEnabled(true);
                
